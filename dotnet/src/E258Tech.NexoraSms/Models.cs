using System;
using System.Collections.Generic;
using System.Text.Json.Serialization;

namespace E258Tech.NexoraSms;

// Read-only results returned by the API. Money is decimal, dates are DateTimeOffset, ids are strings (UUID).
// Unknown JSON fields are ignored; missing lists come back empty.

/// <summary>Result of <see cref="MessagesResource.SendAsync"/>: one campaign per channel.</summary>
public sealed record SendMessageResult
{
    /// <summary>One entry per channel sent.</summary>
    public IReadOnlyList<SentChannel> Channels { get; init; } = Array.Empty<SentChannel>();

    /// <summary>Recipients rejected by the API (invalid phone or email); nothing was sent to them.</summary>
    public IReadOnlyList<string> Invalid { get; init; } = Array.Empty<string>();

    /// <summary>The Idempotency-Key used by this call (given in the request or generated by the SDK).</summary>
    [JsonIgnore]
    public string IdempotencyKey { get; init; } = "";

    /// <summary>True when the API answered with a stored result (<c>Idempotent-Replayed: true</c>): nothing new was sent.</summary>
    [JsonIgnore]
    public bool Replayed { get; init; }
}

/// <summary>One channel of a send.</summary>
public sealed record SentChannel
{
    /// <summary>Channel.</summary>
    public Channel Channel { get; init; }

    /// <summary>Campaign created for this channel.</summary>
    public string CampaignId { get; init; } = "";

    /// <summary>Number of recipients on this channel.</summary>
    public int Recipients { get; init; }

    /// <summary>Cost reserved for this channel.</summary>
    public decimal Cost { get; init; }

    /// <summary>Campaign status.</summary>
    public CampaignStatus Status { get; init; }
}

/// <summary>Result of <see cref="MessagesResource.EstimateAsync"/>. Nothing is sent.</summary>
public sealed record EstimateResult
{
    /// <summary>Estimate per channel.</summary>
    public IReadOnlyList<ChannelEstimate> Channels { get; init; } = Array.Empty<ChannelEstimate>();

    /// <summary>Total cost.</summary>
    public decimal Total { get; init; }

    /// <summary>Wallet balance available.</summary>
    public decimal Available { get; init; }

    /// <summary>Recipients that would be rejected.</summary>
    public IReadOnlyList<string> Invalid { get; init; } = Array.Empty<string>();
}

/// <summary>Estimate for one channel.</summary>
public sealed record ChannelEstimate
{
    /// <summary>Channel.</summary>
    public Channel Channel { get; init; }

    /// <summary>Number of recipients.</summary>
    public int Recipients { get; init; }

    /// <summary>Segments per message (SMS).</summary>
    public int Segments { get; init; }

    /// <summary>Text encoding.</summary>
    public MessageEncoding Encoding { get; init; }

    /// <summary>Price per segment or message.</summary>
    public decimal UnitPrice { get; init; }

    /// <summary>Cost of this channel.</summary>
    public decimal Cost { get; init; }
}

/// <summary>A message to one destination.</summary>
public sealed record Message
{
    /// <summary>Message id.</summary>
    public string Id { get; init; } = "";

    /// <summary>Campaign id.</summary>
    public string CampaignId { get; init; } = "";

    /// <summary>Channel.</summary>
    public Channel Channel { get; init; }

    /// <summary>Phone (E.164) or email address.</summary>
    public string Destination { get; init; } = "";

    /// <summary>Status.</summary>
    public MessageStatus Status { get; init; }

    /// <summary>Cost.</summary>
    public decimal Cost { get; init; }

    /// <summary>Number of parts (SMS segments).</summary>
    public int Parts { get; init; }

    /// <summary>When it was created.</summary>
    public DateTimeOffset CreatedAt { get; init; }

    /// <summary>When the provider accepted it.</summary>
    public DateTimeOffset? AcceptedAt { get; init; }

    /// <summary>When it was delivered.</summary>
    public DateTimeOffset? DeliveredAt { get; init; }

    /// <summary>Delivery attempts to the provider.</summary>
    public IReadOnlyList<MessageAttempt> Attempts { get; init; } = Array.Empty<MessageAttempt>();

    /// <summary>Campaign name.</summary>
    public string? CampaignName { get; init; }

    /// <summary>Sender ID or sender address.</summary>
    public string? Sender { get; init; }

    /// <summary>Email subject.</summary>
    public string? Subject { get; init; }

    /// <summary>Content.</summary>
    public string? Content { get; init; }

    /// <summary>WhatsApp template name.</summary>
    public string? Template { get; init; }

    /// <summary>WhatsApp template language.</summary>
    public string? Language { get; init; }
}

/// <summary>One attempt to hand a message part to the provider.</summary>
public sealed record MessageAttempt
{
    /// <summary>Part number (from 1).</summary>
    public int PartNumber { get; init; }

    /// <summary>Attempt number (from 1).</summary>
    public int AttemptNumber { get; init; }

    /// <summary>Status.</summary>
    public AttemptStatus Status { get; init; }

    /// <summary>Provider's message id.</summary>
    public string? ProviderMessageId { get; init; }

    /// <summary>Provider's error code when it failed.</summary>
    public string? ErrorCode { get; init; }

    /// <summary>When it started.</summary>
    public DateTimeOffset StartedAt { get; init; }

    /// <summary>When it finished.</summary>
    public DateTimeOffset? CompletedAt { get; init; }
}

/// <summary>A contact.</summary>
public sealed record Contact
{
    /// <summary>Contact id.</summary>
    public string Id { get; init; } = "";

    /// <summary>Name.</summary>
    public string? Name { get; init; }

    /// <summary>Phone in E.164.</summary>
    public string? Phone { get; init; }

    /// <summary>Email.</summary>
    public string? Email { get; init; }

    /// <summary>Status.</summary>
    public ContactStatus Status { get; init; }

    /// <summary>Groups.</summary>
    public IReadOnlyList<string> GroupIds { get; init; } = Array.Empty<string>();

    /// <summary>Tags.</summary>
    public IReadOnlyList<string> Tags { get; init; } = Array.Empty<string>();

    /// <summary>Consents per channel.</summary>
    public IReadOnlyList<Consent> Consents { get; init; } = Array.Empty<Consent>();

    /// <summary>When it was created.</summary>
    public DateTimeOffset CreatedAt { get; init; }

    /// <summary>Custom fields (names kept exactly as stored).</summary>
    public IReadOnlyDictionary<string, string?> Attributes { get; init; } = new Dictionary<string, string?>();

    /// <summary>Id of the contact in your system.</summary>
    public string? ExternalId { get; init; }
}

/// <summary>Consent of a contact for one channel.</summary>
public sealed record Consent
{
    /// <summary>Channel.</summary>
    public Channel Channel { get; init; }

    /// <summary>Granted or revoked.</summary>
    public ConsentStatus Status { get; init; }

    /// <summary>Where it came from (e.g. <c>erp</c>).</summary>
    public string Source { get; init; } = "";

    /// <summary>When it was recorded.</summary>
    public DateTimeOffset RecordedAt { get; init; }
}

/// <summary>A page of results.</summary>
/// <typeparam name="T">Item type.</typeparam>
public sealed record Page<T>
{
    /// <summary>Items on this page.</summary>
    public IReadOnlyList<T> Items { get; init; } = Array.Empty<T>();

    /// <summary>Page number (from 1). JSON <c>page</c>.</summary>
    [JsonPropertyName("page")]
    public int PageNumber { get; init; }

    /// <summary>Page size.</summary>
    public int PageSize { get; init; }

    /// <summary>Total items across all pages.</summary>
    public int Total { get; init; }
}

/// <summary>The company's wallet.</summary>
public sealed record Wallet
{
    /// <summary>Currency (e.g. <c>MZN</c>).</summary>
    public string Currency { get; init; } = "";

    /// <summary>Balance.</summary>
    public decimal Balance { get; init; }

    /// <summary>Amount reserved for sends in progress.</summary>
    public decimal Reserved { get; init; }

    /// <summary>Balance available for new sends.</summary>
    public decimal Available { get; init; }
}

/// <summary>A wallet transaction.</summary>
public sealed record WalletTransaction
{
    /// <summary>Transaction id.</summary>
    public string Id { get; init; } = "";

    /// <summary>Type.</summary>
    public WalletTransactionType Type { get; init; }

    /// <summary>Amount.</summary>
    public decimal Amount { get; init; }

    /// <summary>Business reference (e.g. campaign or top-up).</summary>
    public string BusinessReference { get; init; } = "";

    /// <summary>Related message.</summary>
    public string? MessageId { get; init; }

    /// <summary>Transaction this one reverses.</summary>
    public string? ReversalOfId { get; init; }

    /// <summary>When it was created.</summary>
    public DateTimeOffset CreatedAt { get; init; }
}

/// <summary>A campaign.</summary>
public sealed record Campaign
{
    /// <summary>Campaign id.</summary>
    public string Id { get; init; } = "";

    /// <summary>Name.</summary>
    public string Name { get; init; } = "";

    /// <summary>Channel.</summary>
    public Channel Channel { get; init; }

    /// <summary>Status.</summary>
    public CampaignStatus Status { get; init; }

    /// <summary>Template used.</summary>
    public string? TemplateId { get; init; }

    /// <summary>Email subject.</summary>
    public string? Subject { get; init; }

    /// <summary>Content.</summary>
    public string Content { get; init; } = "";

    /// <summary>Number of recipients.</summary>
    public int Recipients { get; init; }

    /// <summary>When it is scheduled to start.</summary>
    public DateTimeOffset? ScheduledAt { get; init; }

    /// <summary>When it was created.</summary>
    public DateTimeOffset CreatedAt { get; init; }

    /// <summary>Whether quiet hours are ignored.</summary>
    public bool IgnoreQuietHours { get; init; }

    /// <summary>Why it was paused.</summary>
    public string? PauseReason { get; init; }

    /// <summary>Sender ID or sender address.</summary>
    public string? Sender { get; init; }

    /// <summary>Messages created.</summary>
    public int? Messages { get; init; }

    /// <summary>Messages delivered.</summary>
    public int? Delivered { get; init; }

    /// <summary>Messages failed.</summary>
    public int? Failed { get; init; }
}

/// <summary>Statistics of a campaign.</summary>
public sealed record CampaignStats
{
    /// <summary>Campaign id.</summary>
    public string CampaignId { get; init; } = "";

    /// <summary>Status.</summary>
    public CampaignStatus Status { get; init; }

    /// <summary>Number of recipients.</summary>
    public int Recipients { get; init; }

    /// <summary>Messages per status (API text, e.g. <c>delivered</c>).</summary>
    public IReadOnlyDictionary<string, int> Messages { get; init; } = new Dictionary<string, int>();

    /// <summary>SMS segments.</summary>
    public int SmsSegments { get; init; }

    /// <summary>Currency.</summary>
    public string Currency { get; init; } = "";

    /// <summary>Estimated cost.</summary>
    public decimal EstimatedCost { get; init; }

    /// <summary>Amount reserved.</summary>
    public decimal Reserved { get; init; }

    /// <summary>Amount debited.</summary>
    public decimal Debited { get; init; }

    /// <summary>Link clicks.</summary>
    public int Clicks { get; init; }

    /// <summary>Unique link clicks.</summary>
    public int UniqueClicks { get; init; }
}
